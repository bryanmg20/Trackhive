import { PrismaAccountErasureMapper } from './prisma-account-erasure.mapper';
import { buildStatusChangeEmail } from '../../application/services/status-change-email';
import { escapeHtml } from '../../../common/html/escape-html';
describe('notification comment redaction', () => {
  it('redacts every occurrence in an unknown template, including escaped HTML variants', () => {
    const comment = 'privado <&>\nlinea';
    const escaped = escapeHtml(comment);
    const row = {
      body: `Formato nuevo: ${comment}; repetido: ${comment}`,
      htmlBody: `<article>${escaped.replace(/\r?\n/g, '<br>')} | ${escaped} | ${comment}</article>`,
    };
    const result = PrismaAccountErasureMapper.notification(row, comment);
    expect(result.body).toBe(
      'Formato nuevo: [Comentario del personal suprimido]; repetido: [Comentario del personal suprimido]',
    );
    expect(result.htmlBody).toBe(
      '<article>[Comentario del personal suprimido] | [Comentario del personal suprimido] | [Comentario del personal suprimido]</article>',
    );
  });
  it.each(['EN_BUSQUEDA', 'RECHAZADA'] as const)(
    'redacts an email generated by the real %s template',
    (newStatus) => {
      const comment = 'privado@example.test <&>\nsegunda línea';
      const mail = buildStatusChangeEmail(
        {
          trackingCode: 'SOL-2026-00042',
          deliveryMode: 'PRESENCIAL',
          requester: {
            firstName: 'Juana',
            lastName: 'Gómez',
            email: 'juana@example.test',
          },
          materials: [{ catalogCode: 'AHB-001', title: 'Actas' }],
          references: [],
        },
        {
          newStatus,
          comment,
          ...(newStatus === 'RECHAZADA' ? { rejectionReason: comment } : {}),
        },
      );
      if (!mail) throw new Error('Expected a notification draft');
      expect(mail.text).toContain(comment);
      expect(mail.html).toContain(
        escapeHtml(comment).replace(/\r?\n/g, '<br>'),
      );
      const result = PrismaAccountErasureMapper.notification(
        { body: mail.text, htmlBody: mail.html ?? null },
        comment,
      );
      expect(result.body).not.toContain('privado@example.test');
      expect(result.htmlBody).not.toContain('privado@example.test');
      expect(result.body).toContain('Juana Gómez');
      expect(result.body).toContain('AHB-001');
      expect(result.body).toContain('[Comentario del personal suprimido]');
    },
  );
  it('leaves empty comments unchanged and does not recursively redact the replacement marker', () => {
    const row = { body: 'Texto', htmlBody: null };
    expect(PrismaAccountErasureMapper.notification(row, '')).toEqual(row);
    expect(PrismaAccountErasureMapper.notification(row, ' \n\t')).toEqual(row);
    const quotedMarker =
      'privado@example.test [Comentario del personal suprimido] firma';
    expect(
      PrismaAccountErasureMapper.notification(
        { body: `Otra plantilla: ${quotedMarker}`, htmlBody: null },
        quotedMarker,
      ).body,
    ).toBe('Otra plantilla: [Comentario del personal suprimido]');
    expect(
      PrismaAccountErasureMapper.notification(
        {
          body: 'Observaciones del personal:\npersonal',
          htmlBody: '<span>personal</span>',
        },
        'personal',
      ).htmlBody,
    ).toBe('<span>[Comentario del personal suprimido]</span>');
  });
  it('preserves citizen data and replaces only the staff slots including HTML escaping', () => {
    const comment = 'Ana <&>\nprivado';
    const row = {
      body: `Hola, Ana:\n\nObservaciones del personal:\n${comment}\n\nMaterial solicitado:\n- Ana`,
      htmlBody:
        '<p>Hola, Ana:</p><p style="margin:0;color:#1e293b;">Ana &lt;&amp;&gt;<br>privado</p><p>Material Ana</p>',
    };
    const result = PrismaAccountErasureMapper.notification(row, comment);
    expect(result.body).toBe(
      'Hola, Ana:\n\nObservaciones del personal:\n[Comentario del personal suprimido]\n\nMaterial solicitado:\n- Ana',
    );
    expect(result.htmlBody).toBe(
      '<p>Hola, Ana:</p><p style="margin:0;color:#1e293b;">[Comentario del personal suprimido]</p><p>Material Ana</p>',
    );
    expect(Object.keys(result).sort()).toEqual(['body', 'htmlBody']);
  });
  it('handles rejection comments and messages without an HTML body', () => {
    expect(
      PrismaAccountErasureMapper.notification(
        { body: 'Motivo del rechazo: privado', htmlBody: null },
        'privado',
      ),
    ).toEqual({
      body: 'Motivo del rechazo: [Comentario del personal suprimido]',
      htmlBody: null,
    });
  });
});
